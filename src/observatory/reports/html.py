def _badge(verdict: Verdict) -> str:
    name = verdict.value
    return f'<span class="badge {name.lower()}">{_MARK[verdict]} {name}</span>'


def render_html(reports: list[AssessmentReport]) -> str:
    """Render one or more reports as a single self-contained HTML page.

    Every report-derived string is escaped: probe output is untrusted text.
    """
    if not reports:
        raise ValueError("at least one report is required")

    lookups = [{r.scenario_id: r for r in rep.results} for rep in reports]
    titles = {r.scenario_id: r.title for rep in reports for r in rep.results}
    scenario_ids = list(titles)

    cards = "".join(
        f'<section class="card"><h2>{escape(rep.runtime)}</h2>'
        f'<p class="meta">{escape(rep.assessment_id)} · {rep.started_at:%Y-%m-%d %H:%M} UTC</p>'
        f'<p>{" ".join(_badge(v) + f" <b>{rep.summary[v.value.lower()]}</b>" for v in Verdict)}</p>'
        "</section>"
        for rep in reports
    )
    head = "".join(f"<th>{escape(rep.runtime)}</th>" for rep in reports)

    rows, details = [], []
    for sid in scenario_ids:
        label = f"<code>{escape(sid)}</code> {escape(titles[sid])}"
        cells = "".join(
            f"<td>{_badge(m[sid].verdict) if sid in m else '—'}</td>" for m in lookups
        )
        rows.append(f"<tr><td>{label}</td>{cells}</tr>")
        items = "".join(
            f"<li><b>{escape(rep.runtime)}</b> {_badge(m[sid].verdict)} {escape(m[sid].reason)}</li>"
            for rep, m in zip(reports, lookups, strict=True)
            if sid in m
        )
        details.append(f"<details><summary>{label}</summary><ul>{items}</ul></details>")

    rows_html, details_html = "".join(rows), "".join(details)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Boundary Assessment Report</title>
<style>{_CSS}</style>
</head>
<body>
<main>
<h1>Agent Boundary Observatory</h1>
<p class="meta">Evidence-based sandbox boundary assessment</p>
<h2>Summary</h2>
<div class="cards">{cards}</div>
<h2>Scenario results</h2>
<div class="table-wrap"><table>
<thead><tr><th>Scenario</th>{head}</tr></thead>
<tbody>{rows_html}</tbody>
</table></div>
<h2>Details</h2>
{details_html}
<footer><p>Generated by Agent Boundary Observatory from the report files.
Passing results do not prove a sandbox is secure.</p></footer>
</main>
</body>
</html>
"""
